// 연설 자료의 저장과 복원을 검증하는 테스트
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 연설읽기, 연설쓰기, 저장가능한가, 연설지우기 } from './talk-store.mjs';

function 가짜저장소(초기 = {}) {
  const 담긴것 = new Map(Object.entries(초기));
  return {
    담긴것,
    async 읽기(경로) { return 담긴것.get(경로) ?? null; },
    async 쓰기(경로, 내용) { 담긴것.set(경로, 내용); },
    async 목록() { return [...담긴것.keys()]; },
    async 지우기(경로) { 담긴것.delete(경로); },
  };
}

const 지금 = () => 1_800_000_000_000;
const 기본 = { 회원번호: '777', 주간: '2026-08-27', 배정번호: 2, 배정제목: '보물 — 징계' };

test('쓴 것을 그대로 읽는다', async () => {
  const 저장소 = 가짜저장소();
  await 연설쓰기({ ...기본, 저장소, 내용: { 뼈대: { 배정시간: 600 } }, 지금 });
  const 읽은것 = await 연설읽기({ ...기본, 저장소 });
  assert.deepEqual(읽은것.뼈대, { 배정시간: 600 });
  assert.equal(읽은것.만든때, new Date(지금()).toISOString());
});

test('정규화된 주간으로 저장한다', async () => {
  const 저장소 = 가짜저장소();
  await 연설쓰기({ ...기본, 저장소, 내용: { 뼈대: {} }, 지금 });
  assert.equal(저장소.담긴것.has('users/777/talks/2026-08-24-2.json'), true);
});

test('같은 주의 다른 날짜로도 찾는다', async () => {
  const 저장소 = 가짜저장소();
  await 연설쓰기({ ...기본, 주간: '2026-08-24', 저장소, 내용: { 뼈대: { 배정시간: 600 } }, 지금 });
  const 읽은것 = await 연설읽기({ ...기본, 주간: '2026-08-30', 저장소 });
  assert.deepEqual(읽은것.뼈대, { 배정시간: 600 });
});

test('없으면 null 이다', async () => {
  assert.equal(await 연설읽기({ ...기본, 저장소: 가짜저장소() }), null);
});

test('배정 제목이 다르면 없는 것으로 본다', async () => {
  const 저장소 = 가짜저장소();
  await 연설쓰기({ ...기본, 저장소, 내용: { 뼈대: {} }, 지금 });
  // 교재 페이지가 고쳐져 순서가 바뀌면 같은 번호가 다른 배정을 가리킨다.
  // 틀린 원고를 맞는 것처럼 보여 주는 쪽이 다시 만드는 것보다 나쁘다.
  const 읽은것 = await 연설읽기({ ...기본, 배정제목: '학생연설 — 다른 것', 저장소 });
  assert.equal(읽은것, null);
});

test('다시 쓰면 덮어쓴다', async () => {
  const 저장소 = 가짜저장소();
  await 연설쓰기({ ...기본, 저장소, 내용: { 뼈대: { 배정시간: 600 } }, 지금 });
  await 연설쓰기({ ...기본, 저장소, 내용: { 뼈대: { 배정시간: 300 } }, 지금 });
  const 읽은것 = await 연설읽기({ ...기본, 저장소 });
  assert.deepEqual(읽은것.뼈대, { 배정시간: 300 });
  assert.equal(저장소.담긴것.size, 1);
});

test('저장이 실패해도 던지지 않는다', async () => {
  const 저장소 = 가짜저장소();
  저장소.쓰기 = async () => {
    throw new Error('저장소가 없다');
  };
  // 원고는 이미 만들어져 화면으로 갈 참이다. 저장 실패로 그것을 잃게 하지 않는다.
  await 연설쓰기({ ...기본, 저장소, 내용: { 뼈대: {} }, 지금 });
});

test('경로를 만들 수 없는 입력은 저장 실패로 삼키지 않고 던진다', async () => {
  const 저장소 = 가짜저장소();
  // 잘못된 입력을 저장소 문제로 덮어 버리면 원인을 못 찾는다.
  await assert.rejects(
    () => 연설쓰기({ ...기본, 배정번호: 1.5, 저장소, 내용: {}, 지금 }),
    /배정번호/);
  await assert.rejects(
    () => 연설쓰기({ ...기본, 회원번호: '../etc', 저장소, 내용: {}, 지금 }),
    /회원번호/);
});

test('읽기가 실패하면 null 이다', async () => {
  const 저장소 = 가짜저장소();
  저장소.읽기 = async () => {
    throw new Error('저장소가 없다');
  };
  assert.equal(await 연설읽기({ ...기본, 저장소 }), null);
});

test('제대로 된 입력이면 저장 가능하다', () => {
  assert.equal(저장가능한가(기본), true);
});

test('indexOf 가 못 찾아 -1 을 주면 저장 불가능하다', () => {
  assert.equal(저장가능한가({ ...기본, 배정번호: -1 }), false);
});

test('배정번호가 정수가 아니면 저장 불가능하다', () => {
  assert.equal(저장가능한가({ ...기본, 배정번호: 1.5 }), false);
});

test('회원번호가 숫자 모양이 아니면 저장 불가능하다', () => {
  assert.equal(저장가능한가({ ...기본, 회원번호: '../etc' }), false);
});

test('주간이 모양에 안 맞으면 저장 불가능하다', () => {
  assert.equal(저장가능한가({ ...기본, 주간: '아무날' }), false);
});

test('지운 뒤에는 읽히지 않는다', async () => {
  const 저장소 = 가짜저장소();
  await 연설쓰기({ ...기본, 저장소, 내용: { 뼈대: {} }, 지금 });
  await 연설지우기({ 저장소, 회원번호: 기본.회원번호, 주간: 기본.주간, 배정번호: 기본.배정번호 });
  assert.equal(await 연설읽기({ ...기본, 저장소 }), null);
});

test('없는 것을 지워도 던지지 않는다', async () => {
  // 두 번 눌렀을 때 오류를 보일 이유가 없다.
  await 연설지우기({ 저장소: 가짜저장소(), 회원번호: '777', 주간: '2026-08-27', 배정번호: 2 });
});

test('배정번호가 올바르지 않으면 던진다', async () => {
  // 잘못된 입력을 저장소 문제로 덮으면 원인을 못 찾는다.
  await assert.rejects(() => 연설지우기({
    저장소: 가짜저장소(), 회원번호: '777', 주간: '2026-08-27', 배정번호: -1,
  }));
});
