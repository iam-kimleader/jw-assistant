// 답변 목록의 소제목·상위질문 머리말이 중복 없이 끼어드는지 검증하는 테스트
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 답변목록펼치기 } from '../web/src/lib/answer-grouping.mjs';

const 답변 = (id, 소제목 = '', 상위질문 = '') => ({ id, 소제목, 상위질문, 질문: id, 답변: '' });
const 종류들 = 목록 => 목록.map(x => x.종류);

test('같은 소제목이 이어지면 머리말은 한 번만 나온다', () => {
  const 펼침 = 답변목록펼치기([답변('a', '첫 소제목'), 답변('b', '첫 소제목')]);
  assert.deepEqual(종류들(펼침), ['소제목', '답변', '답변']);
});

test('소제목이 바뀌면 머리말을 다시 찍는다', () => {
  const 펼침 = 답변목록펼치기([답변('a', '첫 소제목'), 답변('b', '둘째 소제목')]);
  assert.deepEqual(종류들(펼침), ['소제목', '답변', '소제목', '답변']);
});

test('같은 상위질문이 이어지면 한 번만 나온다', () => {
  const 펼침 = 답변목록펼치기([답변('a', '', '상위'), 답변('b', '', '상위')]);
  assert.deepEqual(종류들(펼침), ['상위질문', '답변', '답변']);
});

test('소제목이 바뀌면 같은 상위질문이라도 다시 찍는다', () => {
  const 펼침 = 답변목록펼치기([답변('a', '첫', '상위'), 답변('b', '둘째', '상위')]);
  assert.deepEqual(종류들(펼침), ['소제목', '상위질문', '답변', '소제목', '상위질문', '답변']);
});

test('상위질문이 없는 답변을 지나면 다음 상위질문을 다시 찍는다', () => {
  const 펼침 = 답변목록펼치기([답변('a', '', '상위'), 답변('b'), 답변('c', '', '상위')]);
  assert.deepEqual(종류들(펼침), ['상위질문', '답변', '답변', '상위질문', '답변']);
});

test('빈 목록과 없는 값도 견딘다', () => {
  assert.deepEqual(답변목록펼치기([]), []);
  assert.deepEqual(답변목록펼치기(undefined), []);
});

test('키는 답변 id 를 쓰고 없으면 순번으로 채운다', () => {
  const 펼침 = 답변목록펼치기([답변('q-1'), { 질문: '무명' }]);
  assert.deepEqual(펼침.map(x => x.키), ['q-1', '답변-1']);
});
