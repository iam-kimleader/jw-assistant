// 카카오 로그인 흐름을 엮는다. HTTP 를 모르므로 어댑터가 결과를 응답으로 옮긴다.
import { 설정경로 } from './storage-paths.mjs';
import { 기본프로필 } from './talk-profile.mjs';

export function 인증만들기({ 설정, 카카오, 저장소, 무작위, 지금 = () => Date.now() }) {
  const 사용자경로 = 설정경로;

  return {
    사용자경로,

    로그인시작() {
      const state = 무작위();
      return { 위치: 카카오.인가주소(설정, state), state };
    },

    async 로그인완료({ code, state, 저장된state, 오류, 오류설명 }) {
      if (!state || !저장된state || state !== 저장된state) {
        return { 결과: '거부', 사유: '로그인 요청이 확인되지 않았습니다. 다시 시도해 주십시오.' };
      }
      if (오류) {
        return { 결과: '거부', 사유: `카카오가 로그인을 거절했습니다. (${오류}: ${오류설명 ?? ''})` };
      }
      if (!code) return { 결과: '거부', 사유: '인가 코드가 없습니다.' };

      let 신원;
      try {
        // 카카오 토큰은 여기서만 쓰고 버린다. 보관하지 않는다.
        const 액세스토큰 = await 카카오.토큰받기(설정, code);
        신원 = await 카카오.사용자정보(액세스토큰);
      } catch (실패) {
        return { 결과: '거부', 사유: 실패.message };
      }

      // 닉네임은 카카오에서 바뀔 수 있으므로 방금 받은 것을 쓴다.
      const 사용자 = { 회원번호: 신원.회원번호, 닉네임: 신원.닉네임 ?? '' };
      const 경로 = 사용자경로(사용자.회원번호);
      const 기록 = await 저장소.읽기(경로);
      if (!기록) {
        // profile.json 은 이제 입장 자격을 정하지 않는다. 카카오 인증이 곧 입장
        // 자격이므로, 이 기록은 닉네임과 첫 로그인 시각을 남기는 부기일 뿐이다.
        // 쓰기가 실패해도 조용히 넘기고 들여보낸다.
        try {
          await 저장소.쓰기(경로, { ...사용자, 첫로그인때: new Date(지금()).toISOString() });
        } catch {
          // 무시한다. 입장은 이미 카카오가 정했다.
        }
      }
      return { 결과: '승인', 사용자 };
    },

    async 설정읽기(회원번호) {
      const 기록 = await 저장소.읽기(설정경로(회원번호));
      // 저장된 뒤에 항목이 늘 수 있다. 기본값 위에 얹어야 화면이 빈칸을 그리지 않는다.
      return { ...기본프로필(), ...(기록?.설정 ?? {}) };
    },

    async 설정쓰기(회원번호, 설정) {
      const 경로 = 설정경로(회원번호);
      const 기록 = (await 저장소.읽기(경로)) ?? {};
      // 브라우저가 보낸 것을 그대로 담지 않는다. 기본프로필 에 있는 열쇠만 통과시킨다.
      const 걸러낸것 = {};
      for (const 열쇠 of Object.keys(기본프로필())) {
        if (열쇠 in 설정) 걸러낸것[열쇠] = 설정[열쇠];
      }
      // 던지는 것을 삼키지 않는다. 형제가 직접 누른 동작이라 실패를 알아야 한다.
      await 저장소.쓰기(경로, { ...기록, 설정: { ...기본프로필(), ...걸러낸것 } });
    },
  };
}
