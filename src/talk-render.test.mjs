// 원고 구조체에서 산출물 네 개를 깎아 내는 렌더를 검증하는 테스트
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { renderTalk } from './talk-render.mjs';

const 시연 = {
  제목: '대화 시작하기 — 호별 방문',
  종류: '시연',
  배정시간: 240,
  지정요점: { 책: '랑제', 과: 3, 요점: 4, 제목: '친절', 요점본문: '친절하고 존중심 있게 말하십시오.' },
  주제성구: null,
  설정: { 등장인물: [{ 역할: '전도인', 설명: '배정된 형제' }], 상황: '토요일 오전 현관', 준비물: ['팜플렛'] },
  구간: [{ 이름: '여는 인사', 시작초: 0, 끝초: 25, 목적: '이름을 밝힌다' }],
  대사: [
    { 구간: '여는 인사', 화자: '전도인', 말: '안녕하세요.', 동작: '반걸음 물러선다', 요점표시: '어조를 낮춰 요점 4를 보인다' },
    { 구간: '여는 인사', 화자: '집주인', 말: '무슨 일이시죠.', 동작: '', 요점표시: '' },
  ],
  단락: [],
  성구: [{ 주소: '예레미야 29:11', 본문: '미래와 희망을 갖게 하려는 것이다.' }],
  축약순서: [{ 순위: 1, 대상: '여는 인사', 사유: '없어도 뜻이 통한다' }],
  출처: [{ 제목: '「랑제」 3과', url: 'https://wol.jw.org/ko/wol/d/r8/lp-ko/1102023303', 조회일: '2026-08-25' }],
  경고: [],
};

const 연설 = {
  ...시연,
  제목: '여호와께서는 자신의 종들을 적절한 정도로 징계하십니다',
  종류: '보물연설',
  배정시간: 600,
  설정: null,
  대사: [],
  단락: [
    { 소제목: '회개하는 유대인들은 여호와를 찾을 것이었습니다', 출처: '교재', 요점: ['징계에는 목적이 있다'], 예화: '자녀를 훈계하는 부모', 적용: '우리도 그렇게 반응한다', 성구주소: ['예레미야 29:11'] },
  ],
};

test('준비용 원고에 설정과 시간 배분과 출처가 다 들어간다', () => {
  const { 준비원고 } = renderTalk(시연);

  assert.match(준비원고, /대화 시작하기 — 호별 방문/);
  assert.match(준비원고, /토요일 오전 현관/);
  assert.match(준비원고, /팜플렛/);
  assert.match(준비원고, /여는 인사/);
  assert.match(준비원고, /「랑제」 3과/);
  assert.match(준비원고, /2026-08-25/);
});

test('낭독용 대본에는 대사와 동작만 남고 배경은 빠진다', () => {
  const { 낭독대본 } = renderTalk(시연);

  assert.match(낭독대본, /안녕하세요\./);
  assert.match(낭독대본, /반걸음 물러선다/);
  assert.ok(!낭독대본.includes('없어도 뜻이 통한다'));
  assert.ok(!낭독대본.includes('2026-08-25'));
});

test('큐카드에는 성구 주소가 있고 성구 본문은 없다', () => {
  const { 큐카드 } = renderTalk(연설);

  assert.match(큐카드, /예레미야 29:11/);
  assert.ok(!큐카드.includes('미래와 희망을 갖게 하려는 것이다'));
});

test('큐카드의 요점은 모두 준비용 원고에도 있다', () => {
  const { 큐카드, 준비원고 } = renderTalk(연설);

  for (const 요점 of 연설.단락[0].요점) {
    assert.ok(큐카드.includes(요점), `큐카드에 없다 — ${요점}`);
    assert.ok(준비원고.includes(요점), `원고에 없다 — ${요점}`);
  }
});

test('자기 점검표는 지정 요점과 요점표시가 붙은 대목을 짝지어 보인다', () => {
  const { 점검표 } = renderTalk(시연);

  assert.match(점검표, /「랑제」 3과 요점 4/);
  assert.match(점검표, /친절하고 존중심 있게 말하십시오/);
  assert.match(점검표, /어조를 낮춰 요점 4를 보인다/);
});

test('요점표시가 하나도 없으면 점검표가 그 사실을 경고한다', () => {
  const { 점검표 } = renderTalk({ ...시연, 대사: [{ 구간: '여는 인사', 화자: '전도인', 말: '안녕하세요.', 동작: '', 요점표시: '' }] });

  assert.match(점검표, /지정 요점을 드러내는 대목이 없습니다/);
});

test('단락만 있는 종류도 단락의 요점표시가 점검표에 잡힌다', () => {
  const { 점검표 } = renderTalk({
    ...연설,
    단락: [{ ...연설.단락[0], 요점표시: '자녀를 훈계하는 부모 예화로 요점 4를 보인다' }],
  });

  assert.match(점검표, /회개하는 유대인들은 여호와를 찾을 것이었습니다/);
  assert.match(점검표, /자녀를 훈계하는 부모 예화로 요점 4를 보인다/);
  assert.ok(!점검표.includes('지정 요점을 드러내는 대목이 없습니다'));
});

test('네 산출물 모두 예상 시간을 같은 값으로 적는다', () => {
  const { 준비원고, 낭독대본, 큐카드, 점검표 } = renderTalk(시연);
  const 꺼내기 = 글 => (글.match(/예상 (\d+분 \d+초)/) || [])[1];

  const 값 = 꺼내기(준비원고);
  assert.ok(값);
  assert.equal(꺼내기(낭독대본), 값);
  assert.equal(꺼내기(큐카드), 값);
  assert.equal(꺼내기(점검표), 값);
});

test('지정 요점이 과 단위로 대체됐으면 준비원고와 점검표가 그 사실을 밝힌다', () => {
  const 대체됨 = { ...시연, 지정요점: { ...시연.지정요점, 대체: true } };
  const { 준비원고, 점검표 } = renderTalk(대체됨);

  assert.match(준비원고, /이것은 「랑제」 3과 전체의 원칙이다\. 요점 4의 본문은 자동으로 가져오지 못했으므로/);
  assert.match(점검표, /이것은 「랑제」 3과 전체의 원칙이다\. 요점 4의 본문은 자동으로 가져오지 못했으므로/);
});

test('지정 요점이 대체되지 않았으면 그 안내를 찍지 않는다', () => {
  const { 준비원고 } = renderTalk(시연);

  assert.ok(!준비원고.includes('자동으로 가져오지 못했으므로'));
});

test('뼈대 단계의 요점배치가 점검표에 보인다', () => {
  const { 점검표 } = renderTalk({ ...시연, 요점배치: '여는 인사' });

  assert.match(점검표, /뼈대 단계에서 정한 배치\. 여는 인사/);
});

test('교재·개요에서 온 소제목은 출처를 밝히지 않는다', () => {
  const { 준비원고 } = renderTalk(연설);

  assert.ok(!준비원고.includes('출처는 교재다'));
});

test('모델이 지어낸 소제목은 교재가 준 것이 아니라고 밝힌다', () => {
  const 생성됨 = {
    ...연설,
    단락: [{ ...연설.단락[0], 출처: '생성' }],
  };
  const { 준비원고 } = renderTalk(생성됨);

  assert.match(준비원고, /이 소제목은 교재가 준 것이 아니다\./);
  assert.ok(!준비원고.includes('출처는 생성다'));
});

test('출처의 조회일이 비었거나 미상이면 낱말을 겹치지 않고 조회일 미상으로 찍는다', () => {
  for (const 조회일 of ['', '조회일 미상']) {
    const 구조체 = { ...시연, 출처: [{ 제목: '「랑제」 3과', url: 'https://wol.jw.org/x', 조회일 }] };
    const { 준비원고 } = renderTalk(구조체);

    assert.match(준비원고, /\(조회일 미상\)/);
    assert.ok(!준비원고.includes('조회일 조회일'), `겹쳤다 — ${조회일}`);
  }
});

test('출처에 실제 조회일이 있으면 그 날짜를 찍는다', () => {
  const { 준비원고 } = renderTalk(시연);

  assert.match(준비원고, /\(조회일 2026-08-25\)/);
});

test('시연이 아니면 낭독대본이 두 사람용이라고 말하지 않는다', () => {
  const { 낭독대본 } = renderTalk(연설);

  assert.ok(!낭독대본.includes('두 사람이 각자 들고 읽는'));
  assert.match(낭독대본, /배경과 근거는 준비용 원고에 있다\./);
});

test('시연은 낭독대본이 두 사람용이라고 말한다', () => {
  const { 낭독대본 } = renderTalk(시연);

  assert.match(낭독대본, /두 사람이 각자 들고 읽는 용도다\./);
});

test('대사에 이미 실린 성구는 낭독대본 끝 목록에서 빠진다', () => {
  const 이미실림 = {
    ...시연,
    대사: [
      { 구간: '성구', 화자: '전도인', 말: '“미래와 희망을 갖게 하려는 것이다.” 라고 합니다.', 동작: '', 요점표시: '' },
    ],
  };
  const { 낭독대본 } = renderTalk(이미실림);

  assert.equal((낭독대본.match(/미래와 희망을 갖게 하려는 것이다/g) ?? []).length, 1);
});

test('대사에 없는 성구는 낭독대본 끝 목록에 그대로 남는다', () => {
  const { 낭독대본 } = renderTalk(시연);

  assert.match(낭독대본, /예레미야 29:11.*미래와 희망을 갖게 하려는 것이다/s);
});

test('준비용 원고와 낭독대본이 성구 보증 범위를 밝힌다', () => {
  const { 준비원고, 낭독대본 } = renderTalk(연설);

  assert.match(준비원고, /신세계역 본문을 그대로 옮긴 곳은 위 성구 1곳뿐이며/);
  assert.match(낭독대본, /신세계역 본문을 그대로 옮긴 곳은 위 성구 1곳뿐이며/);
});

test('성구가 없으면 신세계역 본문이 없다고 밝힌다', () => {
  const { 준비원고 } = renderTalk({ ...시연, 성구: [] });

  assert.match(준비원고, /이 원고에는 신세계역 본문이 들어 있지 않다\./);
});

test('경고가 있으면 준비용 원고 맨 위에 뜬다', () => {
  const { 준비원고 } = renderTalk({ ...시연, 경고: ['성구 자동 확인 실패 — 없는책 1:1'] });

  assert.match(준비원고.split('\n').slice(0, 8).join('\n'), /성구 자동 확인 실패/);
});
