// 성구 주소 치환과 모델 성구 위반 검사를 검증하는 테스트
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 성구채우기, 모델성구검사 } from './talk-verses.mjs';

const 가짜읽기 = 주소 => (주소 === '예레미야 29:11' ? '내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다.' : null);

function 구조체(덮어쓰기 = {}) {
  return { 대사: [], 단락: [], 성구: [], 경고: [], ...덮어쓰기 };
}

test('유효한 주소를 로컬 본문으로 채운다', () => {
  const 결과 = 성구채우기(구조체({ 성구: [{ 주소: '예레미야 29:11', 본문: '' }] }), 가짜읽기);

  assert.equal(결과.성구[0].본문, '내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다.');
  assert.deepEqual(결과.경고, []);
});

test('모델이 써 넣은 본문을 덮어쓴다', () => {
  const 결과 = 성구채우기(구조체({ 성구: [{ 주소: '예레미야 29:11', 본문: '모델이 지어낸 문장이다.' }] }), 가짜읽기);

  assert.equal(결과.성구[0].본문, '내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다.');
});

test('해석 못 한 주소는 본문을 비우고 경고를 남긴다', () => {
  const 결과 = 성구채우기(구조체({ 성구: [{ 주소: '없는책 1:1', 본문: '모델이 지어낸 문장이다.' }] }), 가짜읽기);

  assert.equal(결과.성구[0].본문, '');
  assert.equal(결과.경고.length, 1);
  assert.match(결과.경고[0], /성구 자동 확인 실패/);
  assert.match(결과.경고[0], /없는책 1:1/);
});

test('단락의 성구주소도 성구 배열로 모은다', () => {
  const 결과 = 성구채우기(구조체({
    단락: [{ 소제목: '가', 출처: '교재', 요점: [], 예화: '', 적용: '', 성구주소: ['예레미야 29:11'] }],
  }), 가짜읽기);

  assert.equal(결과.성구.length, 1);
  assert.equal(결과.성구[0].주소, '예레미야 29:11');
});

test('같은 주소를 두 번 담지 않는다', () => {
  const 결과 = 성구채우기(구조체({
    성구: [{ 주소: '예레미야 29:11', 본문: '' }],
    단락: [{ 소제목: '가', 출처: '교재', 요점: [], 예화: '', 적용: '', 성구주소: ['예레미야 29:11'] }],
  }), 가짜읽기);

  assert.equal(결과.성구.length, 1);
});

test('대사 안 자리표시자를 로컬 본문으로 바꾼다', () => {
  const 결과 = 성구채우기(구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: '읽어 드리겠습니다. {{성구:예레미야 29:11}}', 동작: '', 요점표시: '' }],
    성구: [{ 주소: '예레미야 29:11', 본문: '' }],
  }), 가짜읽기);

  assert.equal(결과.대사[0].말, '읽어 드리겠습니다. “내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다.”');
});

// 실제 원고(activities/talks/2026-08-24/대화-시작하기-호별-방문-원고.md)의
// 인용부호 구간 20개를 전수 조사한 결과다. 정당한 인용이 139자까지, 진짜 성구
// 인용이 95자라 길이로는 위조를 가려낼 수 없었다(실측). 그래서 검사는 인용부호
// 바로 앞에 성구 주소가 붙어 있는지로 가린다.

test('모델이 성구 주소를 붙이고 다른 문장을 인용하면 위반으로 잡는다', () => {
  const 검사 = 모델성구검사(구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: '예레미야 29:11은 “내가 지어낸 문장이다” 라고 합니다.', 동작: '', 요점표시: '' }],
  }), 가짜읽기);

  assert.equal(검사.통과, false);
  assert.equal(검사.위반.length, 1);
  assert.match(검사.위반[0], /모델이 성구 문장을 직접 썼다/);
});

test('짧은 조작 인용도 성구 주소가 붙어 있으면 거절한다', () => {
  const 시편읽기 = 주소 => (주소 === '시 23:1' ? '여호와는 나의 목자시니 내게 부족함이 없으리로다.' : null);
  const 검사 = 모델성구검사(구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: '시 23:1은 “내가 지어낸 짧은 문장” 이다.', 동작: '', 요점표시: '' }],
  }), 시편읽기);

  assert.equal(검사.통과, false);
  assert.equal(검사.위반.length, 1);
});

test('성구 주소가 붙었어도 로컬 본문 그대로 인용하면 통과한다', () => {
  const 검사 = 모델성구검사(구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: '예레미야 29:11은 “내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다.” 라고 말합니다.', 동작: '', 요점표시: '' }],
  }), 가짜읽기);

  assert.equal(검사.통과, true);
});

test('읽기를 안 주면 인용부호가 있어도 아무것도 거절하지 않는다', () => {
  const 검사 = 모델성구검사(구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: '예레미야 29:11은 “내가 지어낸 문장이다” 라고 합니다.', 동작: '', 요점표시: '' }],
  }));

  assert.equal(검사.통과, true);
});

test('자리표시자를 쓴 대사는 위반이 아니다', () => {
  const 검사 = 모델성구검사(구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: '{{성구:예레미야 29:11}}', 동작: '', 요점표시: '' }],
    성구: [{ 주소: '예레미야 29:11', 본문: '' }],
  }), 가짜읽기);

  assert.equal(검사.통과, true);
});

test('짧은 인용부호는 성구 주소가 없으면 위반이 아니다', () => {
  const 검사 = 모델성구검사(구조체({
    대사: [{ 구간: '화제', 화자: '집주인', 말: '그런 건 좀 “종교” 얘기 아닌가요.', 동작: '', 요점표시: '' }],
  }), 가짜읽기);

  assert.equal(검사.통과, true);
});

test('단락의 요점·예화·적용에서도 성구 주소가 붙은 조작 인용을 잡는다', () => {
  const 검사 = 모델성구검사(구조체({
    단락: [{
      소제목: '가', 출처: '교재',
      요점: ['예레미야 29:11은 “내가 지어낸 문장이다” 라고 합니다.'],
      예화: '예레미야 29:11은 “여기도 지어낸 문장이다” 라고 합니다.',
      적용: '', 성구주소: [],
    }],
  }), 가짜읽기);

  assert.equal(검사.통과, false);
  assert.deepEqual(검사.단락위반, [0]);
  assert.equal(검사.위반.length, 2);
});

test('단락의 소제목은 검사하지 않는다', () => {
  const 검사 = 모델성구검사(구조체({
    단락: [{
      소제목: '예레미야 29:11은 “내가 지어낸 문장이다” 라고 합니다.',
      출처: '교재', 요점: [], 예화: '', 적용: '', 성구주소: [],
    }],
  }), 가짜읽기);

  assert.equal(검사.통과, true);
});

test('실제 원고의 정당한 인용 다섯이 전부 통과한다', () => {
  const 랑제요점원문 = '“친절하고 존중심 있게 말하십시오. 우리가 상대방을 염려하고 진정으로 돕고 싶은 마음이 있으면, 우리가 말하는 방식에 그 점이 드러날 것입니다. 무슨 말을 어떤 어조로 할지 신중하게 생각한 다음 말하십시오. 기분을 상하게 할 만한 말은 하지 마십시오.” — 「랑제」 3과 요점 4 원문은 이렇다.';
  const 팜플렛인용 = '팜플렛 2과 1항이 “성경은 밝은 「미래」를 약속하며 그 약속은 우리에게 「희망」을 줍니다. (예레미야 29:11, 12을 읽어 보세요.)” 라고 말한다.';
  const 집주인대사인용 = '> 〔요점 4〕 반박하지 않는다. “그렇게 보실 수 있습니다. 저도 예전에 그랬고요”로 받는다.';
  const 짧은인용17자 = '> 〔대사〕 “종교 하시는 분들 얘기 아닌가요”';
  const 짧은인용2자 = '집주인 대사. “음⋯”';

  const 검사 = 모델성구검사(구조체({
    단락: [{
      소제목: '가', 출처: '교재', 요점: [], 성구주소: [],
      예화: [랑제요점원문, 팜플렛인용, 집주인대사인용, 짧은인용17자, 짧은인용2자].join(' '),
      적용: '',
    }],
  }), 가짜읽기);

  assert.equal(검사.통과, true, JSON.stringify(검사.위반));
});

test('단락 적용 안 자리표시자를 로컬 본문으로 바꾼다', () => {
  const 결과 = 성구채우기(구조체({
    단락: [{ 소제목: '가', 출처: '교재', 요점: [], 예화: '', 적용: '{{성구:예레미야 29:11}} 을 낭독한 뒤 적용합니다.', 성구주소: [] }],
  }), 가짜읽기);

  assert.equal(결과.단락[0].적용, '“내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다.” 을 낭독한 뒤 적용합니다.');
  assert.ok(!결과.단락[0].적용.includes('{{'));
});

test('단락 요점 배열 안 자리표시자도 치환된다', () => {
  const 결과 = 성구채우기(구조체({
    단락: [{ 소제목: '가', 출처: '교재', 요점: ['{{성구:예레미야 29:11}} 이 요점입니다.'], 예화: '', 적용: '', 성구주소: [] }],
  }), 가짜읽기);

  assert.match(결과.단락[0].요점[0], /“내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다\.”/);
});

test('단락 안 해석 못 한 주소는 자리표시자를 그대로 두고 경고를 남긴다', () => {
  const 결과 = 성구채우기(구조체({
    단락: [{ 소제목: '가', 출처: '교재', 요점: [], 예화: '{{성구:없는책 1:1}} 예화입니다.', 적용: '', 성구주소: [] }],
  }), 가짜읽기);

  assert.equal(결과.단락[0].예화, '{{성구:없는책 1:1}} 예화입니다.');
  assert.ok(결과.경고.some(x => /성구 자동 확인 실패/.test(x) && x.includes('없는책 1:1')));
});

test('단락 소제목의 자리표시자 모양 문자열은 치환되지 않는다', () => {
  const 결과 = 성구채우기(구조체({
    단락: [{ 소제목: '{{성구:예레미야 29:11}}', 출처: '교재', 요점: [], 예화: '', 적용: '', 성구주소: [] }],
  }), 가짜읽기);

  assert.equal(결과.단락[0].소제목, '{{성구:예레미야 29:11}}');
});
