// 연설 자료를 사람별로 보관한다. 배정 번호가 가리키는 대상이 바뀌었으면 복원하지 않는다.
import { 연설경로 } from './storage-paths.mjs';

export async function 연설읽기({ 저장소, 회원번호, 주간, 배정번호, 배정제목 }) {
  const 경로 = 연설경로(회원번호, 주간, 배정번호);
  const 담긴것 = await 저장소.읽기(경로).catch(() => null);
  if (!담긴것) return null;
  // 교재 페이지가 고쳐져 배정 순서가 바뀌면 같은 번호가 다른 배정을 가리킨다.
  // 틀린 원고를 맞는 것처럼 보여 주는 쪽이 다시 만드는 것보다 나쁘다.
  if (담긴것.배정제목 !== 배정제목) return null;
  return 담긴것;
}

export async function 연설쓰기({
  저장소, 회원번호, 주간, 배정번호, 배정제목, 내용, 지금 = () => Date.now(),
}) {
  // 경로 만들기는 try 밖에 둔다. 잘못된 입력을 저장소 문제로 덮으면 원인을 못 찾는다.
  const 경로 = 연설경로(회원번호, 주간, 배정번호);
  try {
    await 저장소.쓰기(경로, {
      배정제목,
      만든때: new Date(지금()).toISOString(),
      ...내용,
    });
  } catch {
    // 원고는 이미 만들어져 화면으로 간다. 저장 실패로 그것을 잃게 하지 않는다.
  }
}
