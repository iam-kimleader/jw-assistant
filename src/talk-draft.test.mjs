      대사: [{ 구간: '여는 인사', 화자: '사회자', 말: '질문입니다.', 동작: '', 요점표시: '' }],
      단락: [{ 소제목: '모델이 만든 소제목', 요점: ['요점'], 예화: '', 적용: '', 성구주소: [] }],
