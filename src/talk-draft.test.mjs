test('단락 예화에 성구 문장을 두 번 다 직접 쓰면 그 칸만 비우고 소제목·성구주소는 남긴다', async () => {
  const 생활부분뼈대 = {
    ...시연뼈대, 종류: '생활부분', 설정: null,
    단락: [{ 소제목: '원래 소제목', 출처: '교재', 요점: [], 예화: '', 적용: '', 성구주소: ['예레미야 29:11'] }],
  };
  const 나쁜단락 = {
    대사: [], 축약순서: [],
    단락: [{ 소제목: '무시될 소제목', 요점: [], 예화: '“내가 너희에 대해 갖고 있는 생각을 나는 잘 알고 있다.”', 적용: '', 성구주소: [] }],
  };
  const 기록 = {};
  const { 구조체 } = await 살채우기({
    뼈대: 생활부분뼈대, 프로필, 매니페스트, 읽기,
    설정: 응답하는([나쁜단락, 나쁜단락], 기록),
  });

  assert.equal(기록.횟수, 2);
  assert.equal(구조체.단락[0].예화, '');
  assert.equal(구조체.단락[0].소제목, '원래 소제목');
  assert.deepEqual(구조체.단락[0].성구주소, ['예레미야 29:11']);
  assert.ok(구조체.경고.some(x => /성구 문장을 직접/.test(x)));
});
