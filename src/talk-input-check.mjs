// 연설 화면이 받는 입력의 검증 규칙. 서버와 브라우저가 같은 규칙을 쓰도록 의존성 없이 떼어 둔다.
export function 공개강연입력검증(입력) {
  const 위반 = [];
  if (!String(입력?.제목 ?? '').trim()) 위반.push('제목이 비어 있습니다.');
  const 소제목 = (입력?.소제목 ?? []).filter(x => String(x?.문장 ?? '').trim());
  if (소제목.length < 2) 위반.push('소제목이 둘 이상 필요합니다.');
  if ((입력?.소제목 ?? []).length !== 소제목.length) 위반.push('빈 소제목 칸이 있습니다.');
  return { 통과: 위반.length === 0, 위반 };
}

// 연설 목표와 들려줄 이야기는 형제가 배정마다 적는다. 두 모델 호출에 그대로 들어가므로
// 브라우저가 보낸 값을 문자열로 바꾸고 상한에서 자른다. 화면도 같은 상한을 maxLength 로 쓴다.
export const 준비메모상한 = { 목표: 500, 이야기: 3000 };

export function 준비메모정리(메모) {
  return {
    목표: String(메모?.목표 ?? '').trim().slice(0, 준비메모상한.목표),
    이야기: String(메모?.이야기 ?? '').trim().slice(0, 준비메모상한.이야기),
  };
}
