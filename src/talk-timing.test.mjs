// 낭독 시간 계산과 축약 제안을 검증하는 테스트
import { test } from 'node:test';
import assert from 'node:assert/strict';
import { 추정초, 시간보고, 분초표기 } from './talk-timing.mjs';

const 설정 = { 분당글자수: 300, 성구계수: 0.5, 동작초: 2 };

function 구조체(덮어쓰기 = {}) {
  return {
    배정시간: 240, 대사: [], 단락: [], 성구: [], 축약순서: [],
    ...덮어쓰기,
  };
}

test('대사 글자 수를 초로 바꾼다', () => {
  const 하나 = 구조체({ 대사: [{ 구간: '가', 화자: '전도인', 말: '가'.repeat(150), 동작: '', 요점표시: '' }] });

  // 150자 / (300자 per 60초) = 30초
  assert.equal(추정초(하나, 설정), 30);
});

test('동작 지시는 글자 수가 아니라 고정 시간으로 센다', () => {
  const 없음 = 구조체({ 대사: [{ 구간: '가', 화자: '전도인', 말: '가'.repeat(150), 동작: '', 요점표시: '' }] });
  const 있음 = 구조체({ 대사: [{ 구간: '가', 화자: '전도인', 말: '가'.repeat(150), 동작: '반걸음 물러선다', 요점표시: '' }] });

  assert.equal(추정초(있음, 설정) - 추정초(없음, 설정), 2);
});

test('성구 낭독은 계수만큼 느리게 센다', () => {
  const 하나 = 구조체({ 성구: [{ 주소: '렘 29:11', 본문: '가'.repeat(150) }] });

  // 150자를 0.5 계수로 = 300자어치 = 60초
  assert.equal(추정초(하나, 설정), 60);
});

test('단락의 요점과 예화와 적용도 글자 수로 센다', () => {
  const 하나 = 구조체({
    단락: [{ 소제목: '가'.repeat(30), 출처: '교재', 요점: ['나'.repeat(60)], 예화: '다'.repeat(30), 적용: '라'.repeat(30), 성구주소: [] }],
  });

  assert.equal(추정초(하나, 설정), 30);
});

test('배정 시간과 초과분을 함께 보고한다', () => {
  const 하나 = 구조체({ 배정시간: 240, 대사: [{ 구간: '가', 화자: '전도인', 말: '가'.repeat(1500), 동작: '', 요점표시: '' }] });
  const 보고 = 시간보고(하나, 설정);

  assert.equal(보고.총초, 300);
  assert.equal(보고.배정초, 240);
  assert.equal(보고.초과, 60);
});

test('시간이 남으면 초과가 음수다', () => {
  const 하나 = 구조체({ 배정시간: 240, 대사: [{ 구간: '가', 화자: '전도인', 말: '가'.repeat(150), 동작: '', 요점표시: '' }] });

  assert.equal(시간보고(하나, 설정).초과, -210);
});

test('축약 순위를 하나씩 적용한 예상 시간을 낸다', () => {
  const 하나 = 구조체({
    배정시간: 240,
    대사: [
      { 구간: '가', 화자: '전도인', 말: '가'.repeat(900), 동작: '', 요점표시: '' },
      { 구간: '나', 화자: '전도인', 말: '나'.repeat(300), 동작: '', 요점표시: '' },
      { 구간: '다', 화자: '전도인', 말: '다'.repeat(300), 동작: '', 요점표시: '' },
    ],
    축약순서: [
      { 순위: 1, 대상: '나', 사유: '없어도 뜻이 통한다' },
      { 순위: 2, 대상: '다', 사유: '앞에서 이미 말했다' },
    ],
  });
  const 보고 = 시간보고(하나, 설정);

  assert.equal(보고.총초, 300);
  assert.deepEqual(보고.축약적용, [{ 순위: 1, 총초: 240 }, { 순위: 2, 총초: 180 }]);
});

test('단락이 축약 대상이 되어도 소제목 문장은 고치지 않는다', () => {
  const 소제목 = '가'.repeat(300);
  const 하나 = 구조체({
    배정시간: 240,
    단락: [{ 소제목, 출처: '교재', 요점: ['나'.repeat(100)], 예화: '', 적용: '', 성구주소: [] }],
    축약순서: [{ 순위: 1, 대상: 소제목, 사유: '길다' }],
  });
  const 보고 = 시간보고(하나, 설정);

  // 요점만 비운 단락과 같은 시간이어야 한다 — 소제목까지 지웠다면 이보다 짧아진다.
  const 요점만비움 = 구조체({
    배정시간: 240,
    단락: [{ 소제목, 출처: '교재', 요점: [], 예화: '', 적용: '', 성구주소: [] }],
  });
  assert.equal(보고.축약적용[0].총초, 추정초(요점만비움, 설정));
});

test('보물 연설 모양에서 소제목 문장을 축약 대상으로 주면 요점·예화·적용이 비고 시간이 준다', () => {
  const 단락 = {
    소제목: '가'.repeat(30), 출처: '교재',
    요점: ['나'.repeat(60)], 예화: '다'.repeat(60), 적용: '라'.repeat(60), 성구주소: ['렘 29:11'],
  };
  const 하나 = 구조체({
    배정시간: 240,
    단락: [단락],
    축약순서: [{ 순위: 1, 대상: 단락.소제목, 사유: '예화와 적용을 줄인다' }],
  });
  const 보고 = 시간보고(하나, 설정);

  const 비운단락만 = 구조체({ 배정시간: 240, 단락: [{ ...단락, 요점: [], 예화: '', 적용: '' }] });
  assert.equal(보고.축약적용[0].총초, 추정초(비운단락만, 설정));
  assert.ok(보고.축약적용[0].총초 < 보고.총초);
});

test('축약 대상이 본론 N 같은 구간 이름이면 그 순서(N-1번째)의 단락이 줄어든다', () => {
  const 단락들 = [
    { 소제목: '하나', 출처: '교재', 요점: ['가'.repeat(90)], 예화: '', 적용: '', 성구주소: [] },
    { 소제목: '둘', 출처: '교재', 요점: ['나'.repeat(90)], 예화: '', 적용: '', 성구주소: [] },
  ];
  const 하나 = 구조체({
    배정시간: 240,
    단락: 단락들,
    축약순서: [{ 순위: 1, 대상: '본론 2', 사유: '' }],
  });
  const 보고 = 시간보고(하나, 설정);

  const 둘째만비움 = 구조체({
    배정시간: 240,
    단락: [단락들[0], { ...단락들[1], 요점: [], 예화: '', 적용: '' }],
  });
  assert.equal(보고.축약적용[0].총초, 추정초(둘째만비움, 설정));
  assert.ok(보고.축약적용[0].총초 < 보고.총초);
});

test('단락을 순위대로 여러 개 축약하면 시간이 단조 감소한다', () => {
  const 단락들 = [
    { 소제목: '하나', 출처: '교재', 요점: ['가'.repeat(90)], 예화: '', 적용: '', 성구주소: [] },
    { 소제목: '둘', 출처: '교재', 요점: ['나'.repeat(90)], 예화: '', 적용: '', 성구주소: [] },
    { 소제목: '셋', 출처: '교재', 요점: ['다'.repeat(90)], 예화: '', 적용: '', 성구주소: [] },
  ];
  const 하나 = 구조체({
    배정시간: 240,
    단락: 단락들,
    축약순서: [
      { 순위: 1, 대상: '본론 1', 사유: '' },
      { 순위: 2, 대상: '본론 2', 사유: '' },
      { 순위: 3, 대상: '본론 3', 사유: '' },
    ],
  });
  const 총초들 = 시간보고(하나, 설정).축약적용.map(x => x.총초);

  assert.ok(총초들[0] < 시간보고(하나, 설정).총초);
  assert.ok(총초들[1] < 총초들[0]);
  assert.ok(총초들[2] < 총초들[1]);
});

test('대사.말 안에 이미 실린 성구 본문은 성구 배열에서 또 세지 않는다', () => {
  const 본문 = '가'.repeat(150);
  const 이중계산됨 = 구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: `읽어 드리겠습니다. “${본문}”`, 동작: '', 요점표시: '' }],
    성구: [{ 주소: '렘 29:11', 본문 }],
  });
  const 대사만 = 구조체({
    대사: [{ 구간: '성구', 화자: '전도인', 말: `읽어 드리겠습니다. “${본문}”`, 동작: '', 요점표시: '' }],
  });

  // 대사.말 글자 수만으로 계산한 것과 같아야 한다 — 성구.본문 을 또 더하면 안 된다.
  assert.equal(추정초(이중계산됨, 설정), 추정초(대사만, 설정));
});

test('단락 예화 안에 이미 실린 성구 본문도 또 세지 않는다', () => {
  const 본문 = '가'.repeat(150);
  const 구조체값 = 구조체({
    단락: [{ 소제목: '가', 출처: '교재', 요점: [], 예화: `“${본문}”`, 적용: '', 성구주소: [] }],
    성구: [{ 주소: '렘 29:11', 본문 }],
  });
  const 단락만 = 구조체({
    단락: [{ 소제목: '가', 출처: '교재', 요점: [], 예화: `“${본문}”`, 적용: '', 성구주소: [] }],
  });

  assert.equal(추정초(구조체값, 설정), 추정초(단락만, 설정));
});

test('성구 본문이 대사·단락 어디에도 없으면 그대로 센다', () => {
  const 하나 = 구조체({ 성구: [{ 주소: '렘 29:11', 본문: '가'.repeat(150) }] });

  assert.equal(추정초(하나, 설정), 60);
});

test('초를 사람이 읽는 표기로 바꾼다', () => {
  assert.equal(분초표기(278), '4분 38초');
  assert.equal(분초표기(240), '4분 0초');
  assert.equal(분초표기(45), '0분 45초');
});
