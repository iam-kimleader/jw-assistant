function 소제목지키기(뼈대, 받은단락) {
  if (!(뼈대.단락 ?? []).length) {
    return (받은단락 ?? []).map(단락 => ({ ...단락, 출처: '생성' }));
  }
  return 뼈대.단락.map((원본, i) => {
    const 받은 = (받은단락 ?? [])[i] ?? {};
    return {
      소제목: 원본.소제목,
      출처: 원본.출처,
      요점: 받은.요점 ?? [],
      예화: 받은.예화 ?? '',
      적용: 받은.적용 ?? '',
      성구주소: [...new Set([...(원본.성구주소 ?? []), ...(받은.성구주소 ?? [])])],
    };
  });
}

// 종류에 따라 대사와 단락 중 한쪽만 남긴다. 준비원고쓰기(talk-render.mjs)가 단락과 대사를
// 각각 '## 원고' 제목 아래 넣으므로, 둘 다 채우면 준비용 원고에 같은 제목이 두 번 나온다.
// 시연은 대사로, 그 밖의 모든 종류는 단락으로 원고를 쓴다.
function 종류별비우기(뼈대, 후보) {
  return 뼈대.종류 === '시연' ? { ...후보, 단락: [] } : { ...후보, 대사: [] };
}

export async function 살채우기({ 뼈대, 프로필, 매니페스트, 읽기, 설정 = {} }) {
  const 자료 = {
    제목: 뼈대.제목, 종류: 뼈대.종류, 배정시간: 뼈대.배정시간,
    구간: 뼈대.구간, 설정: 뼈대.설정, 지정요점: 뼈대.지정요점,
    소제목: (뼈대.단락 ?? []).map(x => ({ 소제목: x.소제목, 출처: x.출처, 성구주소: x.성구주소 })),
    화자: { 성별: 프로필.성별, 연령: 프로필.연령, 임명: 프로필.임명, 파이오니아: 프로필.파이오니아, 스타일: 프로필.스타일 },
    문체견본: String(프로필.문체견본 ?? '').slice(0, 2000),
  };

  let 마지막경고 = '';
  for (const 되풀이 of [false, true]) {
    const { 결과, 생성 } = await 구조화생성({
      지시: 지시만들기(뼈대, 되풀이), 자료, 스키마, 스키마이름: '연설원고', 설정,
    });
    마지막경고 = 생성.warning;
    if (!결과) break;

    const 후보 = {
      ...뼈대,
      대사: 결과.대사 ?? [],
      단락: 소제목지키기(뼈대, 결과.단락),
      축약순서: 결과.축약순서 ?? [],
    };
    // 비우기 전에 모델이 실제로 돌려준 대사와 단락을 검사한다. 먼저 비우면 비운 채널은
    // 영원히 통과해 버려 그 채널의 성구 위반을 놓친다.
    const 검사 = 모델성구검사(후보, 읽기);
    if (검사.통과) return { 구조체: 성구채우기(종류별비우기(뼈대, 후보), 읽기), 생성 };
    if (되풀이) {
      // 위반한 단락만 요점·예화·적용을 비운다. 소제목·출처·성구주소는 교재·개요 원문이라 남긴다.
      const 단락정리 = 후보.단락.map((단락, i) =>
        검사.단락위반.includes(i) ? { ...단락, 요점: [], 예화: '', 적용: '' } : 단락
      );
      const 막은것 = 종류별비우기(뼈대, {
        ...후보, 대사: [], 단락: 단락정리, 경고: [...(뼈대.경고 ?? []), ...검사.위반],
      });
      return { 구조체: 성구채우기(막은것, 읽기), 생성 };
    }
  }

  const 그대로 = { ...뼈대, 경고: [...(뼈대.경고 ?? []), 마지막경고 || '원고를 생성하지 못했습니다.'] };
  return { 구조체: 성구채우기(그대로, 읽기), 생성: { mode: 'fallback', warning: 마지막경고 } };
}
