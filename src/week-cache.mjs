// 주간 자료는 사람과 무관하므로 한 번 만들어 회중이 나눠 쓴다. 그 판단을 여기 모은다.
import { 주간열쇠, 주간경로 } from './storage-paths.mjs';

export async function 주간자료가져오기({
  종류,
  날짜,
  저장소,
  만들기,
  다시만들기 = false,
  지금 = () => Date.now(),
}) {
  // 경로 만들기는 try 밖에 둔다. 여기서 던지는 것은 잘못된 입력이지 저장소 문제가 아니다.
  const 경로 = 주간경로(종류, 날짜);
  const 주간 = 주간열쇠(날짜);

  if (!다시만들기) {
    // 읽기 는 없거나 판이 다르거나 실패하면 null 을 준다. store.mjs 가 이미 삼킨다.
    const 담긴것 = await 저장소.읽기(경로).catch(() => null);
    if (담긴것?.자료) {
      return { 자료: 담긴것.자료, 만든때: 담긴것.만든때 ?? null, 새로만듦: false };
    }
  }

  // 만들기 가 던지는 것은 삼키지 않는다. 자료를 못 만든 것은 화면이 알아야 한다.
  const 자료 = await 만들기(주간);
  const 만든때 = new Date(지금()).toISOString();

  try {
    await 저장소.쓰기(경로, { 자료, 만든때 });
  } catch {
    // 이 시점에 OpenAI 호출은 끝났고 돈은 이미 나갔다.
    // 저장 실패로 결과를 잃게 하는 쪽이 훨씬 나쁘다. 다음에 열면 없을 뿐이다.
  }

  return { 자료, 만든때, 새로만듦: true };
}
