// 답변 목록을 소제목과 상위질문 머리말이 끼어든 평평한 목록으로 펼친다.

// 같은 소제목이 이어지면 한 번만 찍는다. 소제목이 바뀌면 상위질문도 다시 찍어야 하므로 기억을 지운다.
export function 답변목록펼치기(답변들) {
  const 결과 = [];
  let 이전소제목 = '';
  let 이전상위질문 = '';

  (답변들 ?? []).forEach((답변, i) => {
    if (답변.소제목 && 답변.소제목 !== 이전소제목) {
      결과.push({ 종류: '소제목', 값: 답변.소제목, 키: `소제목-${i}` });
      이전소제목 = 답변.소제목;
      이전상위질문 = '';
    }
    if (답변.상위질문 && 답변.상위질문 !== 이전상위질문) {
      결과.push({ 종류: '상위질문', 값: 답변.상위질문, 키: `상위질문-${i}` });
      이전상위질문 = 답변.상위질문;
    } else if (!답변.상위질문) {
      이전상위질문 = '';
    }
    결과.push({ 종류: '답변', 값: 답변, 키: 답변.id ?? `답변-${i}` });
  });

  return 결과;
}
